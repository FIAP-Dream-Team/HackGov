-- ---------------------------------------------------------------------
-- UNIDADE_SAUDE: UBS de origem e unidade onde o horário acontece.
-- ENDERECO é atributo composto, decomposto em colunas atômicas.
-- ---------------------------------------------------------------------
CREATE TABLE UNIDADE_SAUDE (
    ID_UNIDADE      NUMBER(10)     NOT NULL,
    NOME            VARCHAR2(120)  NOT NULL,
    CNES            CHAR(7),
    TIPO_UNIDADE    VARCHAR2(15)   NOT NULL,
    LOGRADOURO      VARCHAR2(120)  NOT NULL,
    NUMERO          VARCHAR2(10)   NOT NULL,
    COMPLEMENTO     VARCHAR2(60),
    BAIRRO          VARCHAR2(60)   NOT NULL,
    CIDADE          VARCHAR2(60)   NOT NULL,
    UF              CHAR(2)        NOT NULL,
    CEP             CHAR(8)        NOT NULL,
    CONSTRAINT PK_UNIDADE_SAUDE PRIMARY KEY (ID_UNIDADE),
    CONSTRAINT UK_UNIDADE_CNES UNIQUE (CNES),
    CONSTRAINT CK_UNIDADE_TIPO CHECK (TIPO_UNIDADE IN ('UBS', 'ESPECIALIZADA'))
);

-- ---------------------------------------------------------------------
-- PESSOA: supertipo. Especialização total e disjunta em CIDADAO e
-- USUARIO_INSTITUCIONAL (uma tabela por subtipo, PK compartilhada).
-- ---------------------------------------------------------------------
CREATE TABLE PESSOA (
    ID_PESSOA       NUMBER(10)     NOT NULL,
    NOME            VARCHAR2(120)  NOT NULL,
    TIPO_PESSOA     CHAR(1)        NOT NULL,
    DATA_CADASTRO   DATE           DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_PESSOA PRIMARY KEY (ID_PESSOA),
    CONSTRAINT CK_PESSOA_TIPO CHECK (TIPO_PESSOA IN ('C', 'U'))
);

-- US01: totem por Cartão SUS ou CPF + nascimento; app por CPF + senha ou Gov.br.
CREATE TABLE CIDADAO (
    ID_PESSOA          NUMBER(10)     NOT NULL,
    CPF                CHAR(11)       NOT NULL,
    CARTAO_SUS         CHAR(15),
    DATA_NASCIMENTO    DATE           NOT NULL,
    SENHA_HASH         VARCHAR2(100),
    ID_GOV_BR          VARCHAR2(64),
    TENTATIVAS_LOGIN   NUMBER(1)      DEFAULT 0 NOT NULL,
    BLOQUEADO_ATE      TIMESTAMP,
    CONSTRAINT PK_CIDADAO PRIMARY KEY (ID_PESSOA),
    CONSTRAINT FK_CIDADAO_PESSOA FOREIGN KEY (ID_PESSOA) REFERENCES PESSOA (ID_PESSOA),
    CONSTRAINT UK_CIDADAO_CPF UNIQUE (CPF),
    CONSTRAINT UK_CIDADAO_CARTAO_SUS UNIQUE (CARTAO_SUS),
    CONSTRAINT UK_CIDADAO_GOV_BR UNIQUE (ID_GOV_BR),
    CONSTRAINT CK_CIDADAO_TENTATIVAS CHECK (TENTATIVAS_LOGIN BETWEEN 0 AND 5)
);

-- US05 / RNF01: equipe e gestor acessam só com login institucional.
CREATE TABLE USUARIO_INSTITUCIONAL (
    ID_PESSOA       NUMBER(10)     NOT NULL,
    ID_UNIDADE      NUMBER(10)     NOT NULL,
    LOGIN           VARCHAR2(40)   NOT NULL,
    SENHA_HASH      VARCHAR2(100)  NOT NULL,
    PERFIL          VARCHAR2(10)   NOT NULL,
    CONSTRAINT PK_USUARIO_INSTITUCIONAL PRIMARY KEY (ID_PESSOA),
    CONSTRAINT FK_USUARIO_PESSOA FOREIGN KEY (ID_PESSOA) REFERENCES PESSOA (ID_PESSOA),
    CONSTRAINT FK_USUARIO_UNIDADE FOREIGN KEY (ID_UNIDADE) REFERENCES UNIDADE_SAUDE (ID_UNIDADE),
    CONSTRAINT UK_USUARIO_LOGIN UNIQUE (LOGIN),
    CONSTRAINT CK_USUARIO_PERFIL CHECK (PERFIL IN ('ATENDENTE', 'GESTOR'))
);

-- Atributo multivalorado "contato" do cidadão, resolvido em tabela própria.
-- Prepara a notificação por SMS/WhatsApp, que o backlog deixou para sprint futura.
CREATE TABLE CONTATO_CIDADAO (
    ID_CONTATO      NUMBER(10)     NOT NULL,
    ID_CIDADAO      NUMBER(10)     NOT NULL,
    TIPO_CONTATO    VARCHAR2(10)   NOT NULL,
    VALOR           VARCHAR2(120)  NOT NULL,
    PRINCIPAL       CHAR(1)        DEFAULT 'N' NOT NULL,
    CONSTRAINT PK_CONTATO_CIDADAO PRIMARY KEY (ID_CONTATO),
    CONSTRAINT FK_CONTATO_CIDADAO FOREIGN KEY (ID_CIDADAO) REFERENCES CIDADAO (ID_PESSOA),
    CONSTRAINT UK_CONTATO_VALOR UNIQUE (ID_CIDADAO, TIPO_CONTATO, VALOR),
    CONSTRAINT CK_CONTATO_TIPO CHECK (TIPO_CONTATO IN ('CELULAR', 'TELEFONE', 'EMAIL')),
    CONSTRAINT CK_CONTATO_PRINCIPAL CHECK (PRINCIPAL IN ('S', 'N'))
);

CREATE TABLE ESPECIALIDADE (
    ID_ESPECIALIDADE  NUMBER(10)   NOT NULL,
    NOME              VARCHAR2(80) NOT NULL,
    CONSTRAINT PK_ESPECIALIDADE PRIMARY KEY (ID_ESPECIALIDADE),
    CONSTRAINT UK_ESPECIALIDADE_NOME UNIQUE (NOME)
);

-- Cada linha é uma vaga publicada. Não há duas vagas no mesmo instante
-- para a mesma especialidade na mesma unidade.
CREATE TABLE HORARIO_DISPONIVEL (
    ID_HORARIO        NUMBER(10)  NOT NULL,
    ID_ESPECIALIDADE  NUMBER(10)  NOT NULL,
    ID_UNIDADE        NUMBER(10)  NOT NULL,
    DATA_HORA         TIMESTAMP   NOT NULL,
    CONSTRAINT PK_HORARIO_DISPONIVEL PRIMARY KEY (ID_HORARIO),
    CONSTRAINT FK_HORARIO_ESPECIALIDADE FOREIGN KEY (ID_ESPECIALIDADE) REFERENCES ESPECIALIDADE (ID_ESPECIALIDADE),
    CONSTRAINT FK_HORARIO_UNIDADE FOREIGN KEY (ID_UNIDADE) REFERENCES UNIDADE_SAUDE (ID_UNIDADE),
    CONSTRAINT UK_HORARIO_VAGA UNIQUE (ID_ESPECIALIDADE, ID_UNIDADE, DATA_HORA),
    -- Alvo da FK composta de AGENDAMENTO (garante a mesma especialidade e a mesma unidade).
    CONSTRAINT UK_HORARIO_ESPEC_UNID UNIQUE (ID_HORARIO, ID_ESPECIALIDADE, ID_UNIDADE)
);

-- US02 / US03: protocolo, 4 status internos e selo de urgência.
-- A quantidade de reagendamentos não é guardada: é contada em AGENDAMENTO
-- (linhas com ID_AGENDAMENTO_ORIGEM preenchido).
-- US03: a unidade de destino é definida no encaminhamento; o cidadão não escolhe outra.
CREATE TABLE ENCAMINHAMENTO (
    ID_ENCAMINHAMENTO   NUMBER(10)    NOT NULL,
    PROTOCOLO           VARCHAR2(20)  NOT NULL,
    DATA_CRIACAO        DATE          DEFAULT SYSDATE NOT NULL,
    STATUS              VARCHAR2(25)  NOT NULL,
    URGENTE             CHAR(1)       DEFAULT 'N' NOT NULL,
    ID_CIDADAO          NUMBER(10)    NOT NULL,
    ID_ESPECIALIDADE    NUMBER(10)    NOT NULL,
    ID_UNIDADE_ORIGEM   NUMBER(10)    NOT NULL,
    ID_UNIDADE_DESTINO  NUMBER(10)    NOT NULL,
    CONSTRAINT PK_ENCAMINHAMENTO PRIMARY KEY (ID_ENCAMINHAMENTO),
    CONSTRAINT UK_ENCAMINHAMENTO_PROTOCOLO UNIQUE (PROTOCOLO),
    -- Alvo da FK composta de AGENDAMENTO (garante a mesma especialidade e a mesma unidade).
    CONSTRAINT UK_ENCAM_ESPEC_UNID UNIQUE (ID_ENCAMINHAMENTO, ID_ESPECIALIDADE, ID_UNIDADE_DESTINO),
    CONSTRAINT FK_ENCAM_CIDADAO FOREIGN KEY (ID_CIDADAO) REFERENCES CIDADAO (ID_PESSOA),
    CONSTRAINT FK_ENCAM_ESPECIALIDADE FOREIGN KEY (ID_ESPECIALIDADE) REFERENCES ESPECIALIDADE (ID_ESPECIALIDADE),
    CONSTRAINT FK_ENCAM_UNIDADE_ORIGEM FOREIGN KEY (ID_UNIDADE_ORIGEM) REFERENCES UNIDADE_SAUDE (ID_UNIDADE),
    CONSTRAINT FK_ENCAM_UNIDADE_DESTINO FOREIGN KEY (ID_UNIDADE_DESTINO) REFERENCES UNIDADE_SAUDE (ID_UNIDADE),
    CONSTRAINT CK_ENCAM_STATUS CHECK (STATUS IN ('RECEBIDO_TRIADO', 'AGUARDANDO_AGENDAMENTO', 'AGENDADO', 'CONCLUIDO')),
    CONSTRAINT CK_ENCAM_URGENTE CHECK (URGENTE IN ('S', 'N'))
);

-- Entidade associativa (agregação) entre ENCAMINHAMENTO e HORARIO_DISPONIVEL.
-- A data e a hora vêm do horário; não são repetidas aqui.
-- O horário é mantido mesmo após o cancelamento, para preservar o histórico.
-- US03 (critério 1): o horário precisa ser da especialidade do encaminhamento.
-- US03: o horário precisa ser da unidade de destino definida no encaminhamento.
-- ID_ESPECIALIDADE e ID_UNIDADE são redundância controlada: participam das duas
-- FKs compostas, então só aceitam o valor que for igual no encaminhamento e no horário.
-- US03 (reagendamento): reagendar encerra o agendamento atual como CANCELADO e
-- cria um novo apontando para ele em ID_AGENDAMENTO_ORIGEM (autorrelacionamento).
-- Cancelar e marcar de novo não preenche a origem, então não conta como reagendamento.
CREATE TABLE AGENDAMENTO (
    ID_AGENDAMENTO          NUMBER(10)    NOT NULL,
    ID_ENCAMINHAMENTO       NUMBER(10)    NOT NULL,
    ID_HORARIO              NUMBER(10)    NOT NULL,
    ID_ESPECIALIDADE        NUMBER(10)    NOT NULL,
    ID_UNIDADE              NUMBER(10)    NOT NULL,
    ID_AGENDAMENTO_ORIGEM   NUMBER(10),
    STATUS                  VARCHAR2(10)  NOT NULL,
    DATA_CRIACAO            TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    DATA_CANCELAMENTO       TIMESTAMP,
    CONSTRAINT PK_AGENDAMENTO PRIMARY KEY (ID_AGENDAMENTO),
    -- Alvo da FK de origem (garante que a origem é do mesmo encaminhamento).
    CONSTRAINT UK_AGEND_ENCAM UNIQUE (ID_AGENDAMENTO, ID_ENCAMINHAMENTO),
    -- Um agendamento é substituído por no máximo um reagendamento.
    CONSTRAINT UK_AGEND_ORIGEM UNIQUE (ID_AGENDAMENTO_ORIGEM),
    CONSTRAINT FK_AGEND_ORIGEM FOREIGN KEY (ID_AGENDAMENTO_ORIGEM, ID_ENCAMINHAMENTO)
        REFERENCES AGENDAMENTO (ID_AGENDAMENTO, ID_ENCAMINHAMENTO),
    CONSTRAINT CK_AGEND_ORIGEM CHECK (ID_AGENDAMENTO_ORIGEM <> ID_AGENDAMENTO),
    CONSTRAINT FK_AGEND_ENCAMINHAMENTO FOREIGN KEY (ID_ENCAMINHAMENTO, ID_ESPECIALIDADE, ID_UNIDADE)
        REFERENCES ENCAMINHAMENTO (ID_ENCAMINHAMENTO, ID_ESPECIALIDADE, ID_UNIDADE_DESTINO),
    CONSTRAINT FK_AGEND_HORARIO FOREIGN KEY (ID_HORARIO, ID_ESPECIALIDADE, ID_UNIDADE)
        REFERENCES HORARIO_DISPONIVEL (ID_HORARIO, ID_ESPECIALIDADE, ID_UNIDADE),
    CONSTRAINT CK_AGEND_STATUS CHECK (STATUS IN ('AGENDADO', 'CANCELADO', 'CONCLUIDO', 'FALTA')),
    CONSTRAINT CK_AGEND_CANCELAMENTO CHECK (
        (STATUS = 'CANCELADO' AND DATA_CANCELAMENTO IS NOT NULL)
        OR (STATUS <> 'CANCELADO' AND DATA_CANCELAMENTO IS NULL)
    )
);

-- US05: toda mudança de etapa registra quem mudou e quando.
-- RESPONSAVEL nulo = mudança feita pelo sistema ou pelo próprio cidadão.
-- STATUS_ANTERIOR nulo = registro de criação do encaminhamento.
CREATE TABLE HISTORICO_STATUS (
    ID_HISTORICO        NUMBER(10)    NOT NULL,
    ID_ENCAMINHAMENTO   NUMBER(10)    NOT NULL,
    STATUS_ANTERIOR     VARCHAR2(25),
    STATUS_NOVO         VARCHAR2(25)  NOT NULL,
    DATA_HORA           TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    ID_RESPONSAVEL      NUMBER(10),
    CONSTRAINT PK_HISTORICO_STATUS PRIMARY KEY (ID_HISTORICO),
    CONSTRAINT FK_HIST_ENCAMINHAMENTO FOREIGN KEY (ID_ENCAMINHAMENTO) REFERENCES ENCAMINHAMENTO (ID_ENCAMINHAMENTO),
    CONSTRAINT FK_HIST_RESPONSAVEL FOREIGN KEY (ID_RESPONSAVEL) REFERENCES USUARIO_INSTITUCIONAL (ID_PESSOA),
    CONSTRAINT CK_HIST_STATUS_ANTERIOR CHECK (STATUS_ANTERIOR IN ('RECEBIDO_TRIADO', 'AGUARDANDO_AGENDAMENTO', 'AGENDADO', 'CONCLUIDO')),
    CONSTRAINT CK_HIST_STATUS_NOVO CHECK (STATUS_NOVO IN ('RECEBIDO_TRIADO', 'AGUARDANDO_AGENDAMENTO', 'AGENDADO', 'CONCLUIDO')),
    -- Toda linha é uma mudança real; no registro de criação (anterior nulo) o CHECK não se aplica.
    CONSTRAINT CK_HIST_MUDANCA CHECK (STATUS_ANTERIOR <> STATUS_NOVO)
);

-- US04 (fora da Sprint 1): painel da sala de espera mostra só senha e sala.
CREATE TABLE CHAMADA (
    ID_CHAMADA        NUMBER(10)    NOT NULL,
    ID_AGENDAMENTO    NUMBER(10)    NOT NULL,
    SENHA             VARCHAR2(10)  NOT NULL,
    SALA              VARCHAR2(20)  NOT NULL,
    DATA_HORA         TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    ID_USUARIO        NUMBER(10)    NOT NULL,
    CONSTRAINT PK_CHAMADA PRIMARY KEY (ID_CHAMADA),
    CONSTRAINT FK_CHAMADA_AGENDAMENTO FOREIGN KEY (ID_AGENDAMENTO) REFERENCES AGENDAMENTO (ID_AGENDAMENTO),
    CONSTRAINT FK_CHAMADA_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO_INSTITUCIONAL (ID_PESSOA)
);

-- ---------------------------------------------------------------------
-- Índices de apoio às consultas das user stories
-- ---------------------------------------------------------------------
CREATE INDEX IX_ENCAM_CIDADAO ON ENCAMINHAMENTO (ID_CIDADAO);                     -- US02: meus encaminhamentos
CREATE INDEX IX_ENCAM_FILA ON ENCAMINHAMENTO (ID_ESPECIALIDADE, STATUS);           -- US05: fila por especialidade
CREATE INDEX IX_HORARIO_BUSCA ON HORARIO_DISPONIVEL (ID_ESPECIALIDADE, DATA_HORA); -- US03: horários livres
CREATE INDEX IX_AGEND_ENCAMINHAMENTO ON AGENDAMENTO (ID_ENCAMINHAMENTO);
CREATE INDEX IX_HIST_ENCAMINHAMENTO ON HISTORICO_STATUS (ID_ENCAMINHAMENTO, DATA_HORA);

-- ---------------------------------------------------------------------
-- Regras de unicidade condicional (índices baseados em função, Oracle)
-- US03: cada encaminhamento tem no máximo 1 horário ativo, e um horário
-- confirmado deixa de existir para outros cidadãos.
-- ---------------------------------------------------------------------
CREATE UNIQUE INDEX UX_AGEND_ATIVO_POR_ENCAM
    ON AGENDAMENTO (CASE WHEN STATUS = 'AGENDADO' THEN ID_ENCAMINHAMENTO END);

CREATE UNIQUE INDEX UX_AGEND_ATIVO_POR_HORARIO
    ON AGENDAMENTO (CASE WHEN STATUS = 'AGENDADO' THEN ID_HORARIO END);
